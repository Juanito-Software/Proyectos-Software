    private void reloadButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_reloadButtonActionPerformed
        int idUser;
        String nombre = jTextFieldNombre.getText();
        String apellido = jTextFieldApellido.getText();
        String dni = jTextFieldDNI.getText();
        String phoneNumber = jTextFieldPhoneNumber.getText();
        String email = jTextFieldEmail.getText();
        String password = jPasswordField.getText();
        String passwordRepeat = jPasswordField.getText();
        String role = (String) jComboBoxRole.getSelectedItem();
        
        
        // Expresiones regulares para validar
        String dniRegex = "^[0-9]{8}[A-Za-z]$"; // 8 dígitos seguidos de una letra
        String phoneRegex = "^[0-9]{9}$"; // Exactamente 9 dígitos
        String emailRegex = "^[A-Za-z0-9+_.-]+@(.+)$";
        
        // Validaciones
        if (nombre.trim().isEmpty() || apellido.trim().isEmpty() || dni.trim().isEmpty() ||
            phoneNumber.trim().isEmpty() || email.trim().isEmpty() || password.trim().isEmpty() || role == null) {
            JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos obligatorios.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        } else if (!dni.matches(dniRegex)) {
            JOptionPane.showMessageDialog(this, "El DNI debe contener 8 números seguidos de una letra.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        } else if (!phoneNumber.matches(phoneRegex)) {
            JOptionPane.showMessageDialog(this, "El número de teléfono debe contener exactamente 9 dígitos.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        } else if (!email.matches(emailRegex)) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese un correo electrónico válido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }else if (!password.equals(passwordRepeat)) {
            JOptionPane.showMessageDialog(null, "Las contraseñas no coinciden.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        idUser=getUserIdByNameAndSurname(nombre, apellido);
        try {
            updateUser(idUser, nombre, apellido, username, dni, phoneNumber, email, password, role);
            System.out.println("Usuario actualizado exitosamente.");
        } catch (Exception e) {
            System.err.println("Error al actualizar el usuario: " + e.getMessage());
            e.printStackTrace(); // Imprime la pila de llamadas para depuración
        }
    }//GEN-LAST:event_reloadButtonActionPerformed

