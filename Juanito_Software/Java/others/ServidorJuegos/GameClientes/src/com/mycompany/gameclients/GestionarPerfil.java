    // Método para cargar los datos del usuario
    private void loadUserData() {
        // Aquí debes implementar la lógica para cargar los datos del usuario desde la base de datos
        // y establecerlos en los campos de texto. Por ejemplo:
        
        try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/juegos", "root", "");
             PreparedStatement stmt = conn.prepareStatement("SELECT * FROM users WHERE username = ?")) {
            
            stmt.setString(1, username);
            ResultSet rs = stmt.executeQuery();
            
            if (rs.next()) {
                jTextFieldNombre.setText(rs.getString("nombre"));
                jTextFieldApellido.setText(rs.getString("apellido"));
                jTextFieldDNI.setText(rs.getString("dni"));
                jTextFieldPhoneNumber.setText(rs.getString("phoneNumber"));
                jTextFieldEmail.setText(rs.getString("email"));
                jPasswordField.setText(rs.getString("password"));
                jPasswordRepeatField.setText(rs.getString("password"));
                userRole = rs.getString("role");
                jComboBoxRole.setSelectedItem(userRole); // Seleccionas ese valor en el combo box
                
                // Llamar al método para ajustar la interfaz según el rol
                adjustUIForRole(userRole);
            }
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al cargar los datos del usuario.");
        }
    }

    
    // Método para ajustar la interfaz según el rol del usuario
    private void adjustUIForRole(String role) {
        if ("admin".equalsIgnoreCase(role)) {
            // Mostrar todos los componentes si es administrador
            jComboBoxRole.setEnabled(true);
        } else {
            // Deshabilitar componentes si no es administrador
            jComboBoxRole.setEnabled(false);
        }
    }
    
    
   
    
