     /**
     * Método que carga el historial de descargas desde un archivo de texto y lo muestra en el área de texto.
     */
    private void loadDownloadHistory() {
        historyArea.setText(""); // Limpiar el área de texto antes de cargar
        try (BufferedReader reader = new BufferedReader(new FileReader("download_history.txt"))) {
            String line;
            while ((line = reader.readLine()) != null) {
                historyArea.append(line + "\n");
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar el historial: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
