    private void Button1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Button1ActionPerformed
        // Confirmación antes de borrar el historial
        int response = JOptionPane.showConfirmDialog(this, "¿Estás seguro de que quieres borrar el historial?", "Confirmación", JOptionPane.YES_NO_OPTION);

        if (response == JOptionPane.YES_OPTION) {
            // Limpiar el archivo de historial
            try (BufferedWriter writer = new BufferedWriter(new FileWriter("download_history.txt"))) {
                writer.write(""); // Esto asegura que el archivo está vacío
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al borrar el historial: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            
            
            // Limpiar el área de texto de historial
            historyArea.setText("");
            try{
                eliminarDescargas();
            }catch(Exception e){
                // Registrar el error para saber qué ocurre
                e.printStackTrace(); // Imprime la traza del error en la consola
                // O puedes mostrar un mensaje informativo
                System.out.println("Error al eliminar descargas: " + e.getMessage());
            }
            // Mostrar mensaje de éxito
            JOptionPane.showMessageDialog(this, "El historial ha sido borrado con éxito.");
        }
    }//GEN-LAST:event_Button1ActionPerformed

